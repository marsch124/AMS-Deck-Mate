/// Remembers the texts copied last, for the "Last copied text" keys. In memory only, and only
/// while a key needs it (`isOn`). What a password manager marks as secret is never kept.
final class ClipboardWatch {
    var onChange: (([String]) -> Void)?
    var isOn = false {
        didSet {
            guard isOn != oldValue else { return }
            timer?.invalidate()
            timer = nil
            texts = []
            guard isOn else { return }
            seen = NSPasteboard.general.changeCount
            take()
            let timer = Timer(timeInterval: 1, repeats: true) { [weak self] _ in self?.look() }
            RunLoop.main.add(timer, forMode: .common)
            self.timer = timer
        }
    }

    private var texts: [String] = []
    private var seen = 0
    private var timer: Timer?
    /// Marks password managers put on what they copy (nspasteboard.org), so it is left alone.
    private static let secret = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
                                 "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword"]

    private func look() {
        let count = NSPasteboard.general.changeCount
        guard count != seen else { return }
        seen = count
        take()
    }

    private func take() {
        let board = NSPasteboard.general
        let types = Set((board.types ?? []).map(\.rawValue))
        guard types.isDisjoint(with: ClipboardWatch.secret) else { return }
        let new = CopiedTexts.after(texts, copied: board.string(forType: .string))
        guard new != texts else { return }
        texts = new
        onChange?(new)
    }
}

/// The files opened last, from the Mac's own record (Spotlight's "last used" date), for the
/// "Recent file" keys. Only looked up while a key needs it (`isOn`).
final class RecentFilesWatch {
    var onChange: (([String]) -> Void)?
    var isOn = false {
        didSet {
            guard isOn != oldValue else { return }
            if isOn { start() } else { stop() }
        }
    }

    private var query: NSMetadataQuery?
    private var watching: [NSObjectProtocol] = []

    private func start() {
        let query = NSMetadataQuery()
        query.searchScopes = [NSMetadataQueryUserHomeScope]
        query.predicate = NSPredicate(format: "kMDItemLastUsedDate >= %@", Date().addingTimeInterval(-604_800) as NSDate)
        query.sortDescriptors = [NSSortDescriptor(key: "kMDItemLastUsedDate", ascending: false)]
        query.notificationBatchingInterval = 5
        for name in [NSNotification.Name.NSMetadataQueryDidFinishGathering, .NSMetadataQueryDidUpdate] {
            watching.append(NotificationCenter.default.addObserver(forName: name, object: query, queue: .main) { [weak self] _ in
                self?.read()
            })
        }
        self.query = query
        query.start()
    }

    private func stop() {
        query?.stop()
        query = nil
        watching.forEach { NotificationCenter.default.removeObserver($0) }
        watching = []
    }

    private func read() {
        guard let query else { return }
        query.disableUpdates()
        var paths: [String] = []
        for index in 0..<min(query.resultCount, 200) {
            guard let item = query.result(at: index) as? NSMetadataItem,
                  let path = item.value(forAttribute: NSMetadataItemPathKey) as? String else { continue }
            let tree = item.value(forAttribute: "kMDItemContentTypeTree") as? [String] ?? []
            if tree.contains("public.folder") || tree.contains("com.apple.application") { continue }
            paths.append(path)
        }
        query.enableUpdates()
        onChange?(RecentFiles.pick(paths, home: NSHomeDirectory()))
    }
}

/// "Bring back an earlier state": the safety copies, newest first; pick one and bring it back.
struct RestoreView: View {
    let copies: [Store.Copy]
    var bringBack: (Store.Copy) -> Void
    var cancel: () -> Void
    @State private var picked: Store.Copy?
    @Environment(\.colorScheme) private var scheme

    var body: some View {
        VStack(alignment: .leading, spacing: 8) {
            Text("Bring back an earlier state").font(.headline).foregroundStyle(Palette.part("screen", scheme))
            Text(copies.isEmpty ? "There are no safety copies yet. One is kept each time your keys change."
                                : "Pick the state to bring back. Your keys as they are now are kept as a safety copy first.")
                .font(.caption).foregroundStyle(.secondary).fixedSize(horizontal: false, vertical: true)
            ScrollView {
                VStack(spacing: 2) {
                    ForEach(Array(copies.enumerated()), id: \.element.id) { index, copy in
                        Button { picked = copy } label: {
                            HStack {
                                Text(copy.date.formatted(date: .abbreviated, time: .shortened))
                                Spacer()
                                Text(copy.words).foregroundStyle(picked == copy ? Color.white.opacity(0.9) : .secondary)
                            }
                            .font(.callout)
                            .foregroundStyle(picked == copy ? Color.white : .primary)
                            .padding(.horizontal, 8)
                            .padding(.vertical, 3)
                            .background(picked == copy ? Palette.fill("screen") : Color.primary.opacity(0.05),
                                        in: RoundedRectangle(cornerRadius: 5, style: .continuous))
                            .contentShape(Rectangle())
                        }
                        .buttonStyle(.plain)
                        .accessibilityIdentifier("copy-\(index)")
                        .accessibilityAddTraits(picked == copy ? .isSelected : [])
                    }
                }
            }
            .frame(height: 230)
            HStack {
                Spacer()
                Button("Cancel", action: cancel)
                    .buttonStyle(PlainButton())
                    .keyboardShortcut(.cancelAction)
                    .accessibilityIdentifier("restoreCancel")
                Button("Bring back") { if let picked { bringBack(picked) } }
                    .buttonStyle(MainButton(part: "screen"))
                    .opacity(picked == nil ? 0.45 : 1)
                    .disabled(picked == nil)
                    .keyboardShortcut(.defaultAction)
                    .accessibilityIdentifier("restoreConfirm")
            }
        }
        .padding(12)
        .frame(width: 400)
    }
}
